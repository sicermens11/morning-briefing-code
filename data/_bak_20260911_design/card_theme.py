def cut(text, n):
    r"""카드에 들어갈 글을 **n자에서 자른다**. 넘으면 뒤에 `…`를 붙인다.

    ⚠️⚠️ **이게 없으면 템플릿화가 성립하지 않는다.** 카드는 1080x1350 고정인데 글은
       매일 길이가 다르다. 2026-08-28 아침, 종목 하나의 `강한신호`가 271자로 와서
       액션플랜 카드가 **547px 넘쳤고** 그날 게시가 통째로 막혔다. 글쓴이에게 매일
       "짧게 써라"를 요구하는 대신, 카드가 알아서 자른다.

    ⚠️ **세로 상세에는 쓰지 않는다.** 거기는 전문이 들어가야 하는 곳이고, 잘린 글은
       `…`로 끝나 무슨 말인지 모르게 된다. 자르는 건 요약본의 몫이다.

    자를 자리는 **띄어쓰기**를 찾는다 — 낱말 가운데서 끊으면 읽다가 걸린다.
    """
    t = (text or "").strip()
    if len(t) <= n:
        return tint_pct(t)
    head = t[:n]
    # ⚠️⚠️ **문장 한가운데서 자르지 않는다** (2026-08-28 지적: "'올라 값…', '어제 이미…'
    #    이렇게 쓰다 말지 말고 제대로 마무리해"). 예산 안에 **끝난 문장**이 있으면
    #    거기서 끊는다 — 그러면 `…` 없이 완결된 글이 된다.
    end = max(head.rfind(m) for m in ("다.", "다!", "다?", ". ", "요."))
    if end >= n * 0.5:
        return tint_pct(t[:end + (2 if t[end:end + 2] in ("다.", "요.") else 1)])
    # 끝난 문장이 없으면 낱말 경계에서 끊고 말줄임을 붙인다.
    sp = head.rfind(" ")
    if sp > n * 0.6:
        head = head[:sp]
    return tint_pct(head.rstrip(" ,·") + "…")


# ⚠️ **부호가 붙은 백분율은 어디에 있든 색을 준다** (2026-08-28 지시).
#    상승 빨강 · 하락 파랑. 표 안의 숫자만 색을 입혔더니 서술 문장 속의 "+6.4%"는
#    까맣게 남아 "상승인데 왜 색이 없냐"는 지적을 받았다. **가로·세로 공용이다.**
#    ⚠️ 부호가 없는 숫자는 건드리지 않는다 — "부채비율 29.58%"는 오르내림이 아니다.
#    ⚠️ 이미 태그가 섞인 글(`<`)은 손대지 않는다. 서술 글은 순수 문자열이다.
_PCT = re.compile(r'([+\-−])(\d[\d,]*(?:\.\d+)?)\s*%')


def tint_pct(text):
    if not text or "<" in str(text):
        return text

    def _sub(m):
        up = m.group(1) == "+"
        return (f'<b style="color:{C["up"] if up else C["down"]}">'
                f'{"+" if up else "−"}{m.group(2)}%</b>')
    return _PCT.sub(_sub, str(text))


def link(text, url):
    r"""문장을 누르면 원문으로 가게 한다 — **주소를 드러내지 않는다**(2026-08-28 요청).

    ⚠️ `http(s)`가 아니면 그냥 글자로 둔다. 카드-copy에 엉뚱한 값이 들어와도
       페이지가 깨지지 않게 하기 위한 것이다.
    ⚠️ 밑줄은 옅게 — 본문 색을 그대로 물려받아 "링크 색"으로 튀지 않게 한다.
    """
    u = str(url or "").strip()
    if not u.startswith(("http://", "https://")):
        return text
    return (f'<a href="{u}" target="_blank" rel="noopener noreferrer" '
            f'style="color:inherit;text-decoration:underline;text-underline-offset:3px;'
            f'text-decoration-color:{C["pill"]}">{text}</a>')


