_편도 = 0.0013
_경계 = "20180101"

세트 = {
    "코스피200 섹터 8": ["코스피 200 건설", "코스피 200 중공업", "코스피 200 철강/소재",
                        "코스피 200 에너지/화학", "코스피 200 정보기술", "코스피 200 금융",
                        "코스피 200 생활소비재", "코스피 200 경기소비재"],
    "코스피 크기 3": ["코스피 대형주", "코스피 중형주", "코스피 소형주"],
    "코스피+코스닥": ["코스피", "코스닥"],
    "코스닥 업종 8": ["제약", "화학", "기계·장비", "전기전자", "의료·정밀기기",
                     "운송장비·부품", "유통", "일반서비스"],
}


def _지수전부():
    """⚠️⚠️ **2016-10-10 하루가 오염돼 있다 (2026-09-02 발견).**
    KRX가 그날 코스닥 업종 지수를 잘못 줬다:
        전기전자 658 → 12,114 (+1741%) → 다음날 −94.7%
        운송장비·부품 −68.6% → 다음날 +215.8% · 일반서비스 −45.4% → +84.6%
    이걸 안 걸렀더니 밴드 리밸런싱이 「폭락한」 섹터를 대량 매수하고 다음날 「폭등」을 먹어
    **배수 6.806(연 +26.8%)이라는 허수**가 나왔다. 다른 주기는 전부 1.7~1.9였다.
    → 지수별로 **하루 변동이 ±25%를 넘으면 그날 값을 직전 값으로 대체**한다.
      (실제 업종 지수가 하루에 25% 움직이는 일은 없다)
    ⚠️ KOSPI는 그날 값이 아예 없어서 예전부터 직전 값을 이어 쓰고 있었다 — 그건 안전하다.
    """
    표 = {}
    for f in sorted(glob.glob(os.path.join(O._DATA, "index-daily", "*.json"))):
        d = json.load(io.open(f, encoding="utf-8-sig"))
        하루 = {}
        for n, v in (d.get("지수") or {}).items():
            c = v.get("종가")
            if c:
                try:
                    하루[n] = float(c)
                except (TypeError, ValueError):
                    pass
        if 하루:
            표[d["기준일"]] = 하루
    # ⚠️⚠️ 첫 판(2026-09-02)에서 **내 로직이 틀렸다.** 이상값일 때 기준값을 갱신하지 않아
    #    한 번 레벨이 바뀌면 그 뒤로 영원히 옛 값과 비교했다:
    #      섬유·의류 2,566건 · 통신 528건 — 둘 다 **오염이 아니라 KRX의 지수 기준 재산정**이다
    #    → 고침: **레벨이 아니라 「그날 수익률」만 죽인다.** 배율을 이어 붙여 새 레벨을 따라간다.
    #      1회성 점프(2016-10-10)든 영구적 레벨 변경이든 **둘 다 올바르게 처리된다.**
    날 = sorted(표)
    앞값, 배율, 고친 = {}, {}, 0
    for d in 날:
        for n, c in list(표[d].items()):
            p = 앞값.get(n)
            앞값[n] = c
            if p and p > 0 and abs(c / p - 1) > 0.25:
                # 그날 수익률을 0으로 본다 = 이후 값을 (직전값/새값) 배율로 끌어온다
                배율[n] = 배율.get(n, 1.0) * (p / c)
                고친 += 1
            m = 배율.get(n)
            if m and abs(m - 1.0) > 1e-12:
                표[d][n] = c * m
    print(f"  ⚠️ 지수 하루변동 ±25% 초과 {고친}건 — 그날 수익률만 0으로 두고 이어 붙였다",
          flush=True)
    return 표


def main():
    print("  자료 읽는 중...", flush=True)
    지 = _지수전부()
    날 = sorted(지)
    print(f"  거래일 {len(날):,}", flush=True)

    # ── ① 섹터 상관 ──
    print("\n  ══ ① 섹터 상관 — **낮아야 분산이 먹힌다** ══")
    for 세트명, 목록 in 세트.items():
        있 = [n for n in 목록 if sum(1 for d in 날 if n in 지[d]) > len(날) * 0.9]
        if len(있) < 2:
            print(f"    {세트명}: 자료 부족")
            continue
        공통 = [d for d in 날 if all(n in 지[d] for n in 있)]
        if len(공통) < 500:
            print(f"    {세트명}: 겹치는 날 부족 ({len(공통)})")
            continue
        수 = {n: [지[공통[k]][n] / 지[공통[k - 1]][n] - 1 for k in range(1, len(공통))]
              for n in 있}
        쌍 = []
        for a in range(len(있)):
            for b in range(a + 1, len(있)):
                A, B = 수[있[a]], 수[있[b]]
                ma, mb = st.mean(A), st.mean(B)
                sa = st.pstdev(A) or 1e-9
                sb = st.pstdev(B) or 1e-9
                쌍.append((sum((A[k] - ma) * (B[k] - mb) for k in range(len(A)))
                           / len(A) / (sa * sb), 있[a], 있[b]))
        쌍.sort()
        평 = st.mean([x[0] for x in 쌍])
        print(f"\n    {세트명} ({len(있)}개 · {len(공통):,}일)  평균 상관 **{평:+.3f}**")
        print(f"      가장 낮은 쌍  {쌍[0][1]} ↔ {쌍[0][2]}  {쌍[0][0]:+.3f}")
        print(f"      가장 높은 쌍  {쌍[-1][1]} ↔ {쌍[-1][2]}  {쌍[-1][0]:+.3f}")
        판 = ("⭐ 분산 효과가 크다" if 평 < 0.5 else
              ("분산 효과가 있다" if 평 < 0.7 else "⚠️ 다 같이 움직인다 — 분산 효과가 작다"))
        print(f"      ⇒ {판}")

    # ── ②③ 리밸런싱 ──
    def 굴리기(목록, 주기, 방식, a, b):
        공통 = [d for d in 날[a:b] if all(n in 지[d] for n in 목록)]
        if len(공통) < 200:
            return None
        N = len(목록)
        # 초기 비중
        def 목표비중(k):
            if 방식 == "동일":
                return [1.0 / N] * N
            창 = 공통[max(0, k - 60):k + 1]
            if len(창) < 30:
                return [1.0 / N] * N
            변 = []
            for n in 목록:
                r = [지[창[z]][n] / 지[창[z - 1]][n] - 1 for z in range(1, len(창))]
                변.append(max(st.pstdev(r), 0.001))
            역 = [1.0 / v for v in 변]
            s = sum(역)
            return [x / s for x in 역]

        w = 목표비중(0)
        총 = 1.0
        몫 = [총 * w[j] / 지[공통[0]][목록[j]] for j in range(N)]
        곡선 = [1.0]
        조정수 = 0
        비용합 = 0.0
        for k in range(1, len(공통)):
            d = 공통[k]
            값 = [몫[j] * 지[d][목록[j]] for j in range(N)]
            총 = sum(값)
            곡선.append(총)
            if 총 <= 0:
                break
            바꿀 = False
            if 주기 == "안함":
                바꿀 = False
            elif 주기 == "밴드":
                목 = 목표비중(k)
                바꿀 = any(abs(값[j] / 총 - 목[j]) > 0.05 for j in range(N))
            else:
                간격 = {"월": 21, "분기": 60, "반기": 122, "연": 245}[주기]
                바꿀 = (k % 간격 == 0)
            if 바꿀:
                목 = 목표비중(k)
                새값 = [총 * 목[j] for j in range(N)]
                옮김 = sum(abs(새값[j] - 값[j]) for j in range(N)) / 2
                비 = 옮김 * _편도 * 2      # 판 쪽 + 산 쪽
                비용합 += 비
                총 -= 비
                새값 = [총 * 목[j] for j in range(N)]
                몫 = [새값[j] / 지[d][목록[j]] for j in range(N)]
                조정수 += 1
        최고, 낙 = 1.0, 0.0
        for x in 곡선:
            최고 = max(최고, x)
            낙 = min(낙, x / 최고 - 1)
        년 = len(공통) / 245
        연 = ((곡선[-1]) ** (1 / 년) - 1) * 100 if 곡선[-1] > 0 else -100
        return 곡선[-1], 연, 낙 * 100, 조정수, 비용합 * 100

    경계i = next(i for i, d in enumerate(날) if d >= _경계)
    구간들 = [("학습 2010~2017", 0, 경계i), ("검증 2018~2026", 경계i, len(날))]
    주기들 = ["안함", "연", "반기", "분기", "월", "밴드"]

    print("\n\n  ══ ②③ 리밸런싱 주기 × 비중 방식 ══")
    print("     ⚠️ 「안함」과 견줘야 **리밸런싱이 값어치가 있는지** 나온다")
    for 세트명, 목록 in 세트.items():
        있 = [n for n in 목록 if sum(1 for d in 날 if n in 지[d]) > len(날) * 0.9]
        if len(있) < 2:
            continue
        print(f"\n  ──── {세트명} ({len(있)}개) ────")
        for 이름, a, b in 구간들:
            공 = [d for d in 날[a:b] if "코스피" in 지[d]]
            if len(공) < 200:
                continue
            배 = 지[공[-1]]["코스피"] / 지[공[0]]["코스피"]
            년 = len(공) / 245
            지연 = (배 ** (1 / 년) - 1) * 100
            최고, 낙지 = 1.0, 0.0
            for d in 공:
                x = 지[d]["코스피"] / 지[공[0]]["코스피"]
                최고 = max(최고, x)
                낙지 = min(낙지, x / 최고 - 1)
            print(f"    {이름}  (코스피 연 {지연:+.1f}% · 낙폭 {낙지*100:.1f}%)")
            print(f"      {'주기':<8}{'비중':<8}{'배수':>8}{'연환산':>9}{'낙폭':>8}"
                  f"{'比':>7}{'조정':>6}{'비용':>7}{'코스피대비':>11}")
            for 방식 in ("동일", "역변동성"):
                for 주기 in 주기들:
                    r = 굴리기(있, 주기, 방식, a, b)
                    if not r:
                        continue
                    자, 연, 낙, 조, 비 = r
                    비율 = 연 / abs(낙) if 낙 else 0
                    표 = "⭐" if 연 > 지연 else "  "
                    print(f"      {주기:<8}{방식:<8}{자:>8.3f}{연:>8.1f}%{낙:>7.1f}%"
                          f"{비율:>7.2f}{조:>6}{비:>6.1f}%{연-지연:>+10.1f}%{표}")
            print()

    print("\n  읽는 법")
    print("    - ①의 평균 상관이 0.7을 넘으면 **섹터가 다 같이 움직인다** = 분산 효과가 작다")
    print("    - ②에서 「분기·월」이 「안함」보다 나아야 **리밸런싱이 값어치가 있다**")
    print("      ⚠️ 안 그러면 그냥 사서 들고 있는 게 낫다는 뜻이다")
    print("    - ⚠️ 지수는 배당을 안 담는다. 실제 ETF는 여기보다 절대 수익이 높다")
    print("      (비교에는 영향이 적다 — 모든 줄에 똑같이 빠져 있다)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
