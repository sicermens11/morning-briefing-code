r"""
rebal_lab.py — **섹터 분산 + 정률 리밸런싱** (2026-09-02 · 28차)

⚠️⚠️ **사용자 요청.**
   *"한 섹터만 보유하면 등락이 심하잖아. 섹터 분산 투자해서, 한 섹터가 떨어지면 다른 섹터가
   오르고, 떨어지는 섹터 매수하고, 오르면 매도해서, 일정 비율을 맞추는 투자법."*

## 이게 지금 막힌 곳과 겹치지 않는 이유
```
24~27차   「개별 종목으로 지수 이기기」 → 전부 실패. 초과가 ±1.5%p 안이었다
28차      「**자산배분**」 — 접근이 완전히 다르다. 종목을 고르는 게 아니라 **비중을 맞춘다**
```

## 정률 리밸런싱이 돈을 버는 원리
```
비중을 고정해 두면 **오른 걸 팔고 떨어진 걸 사게 된다** (자동 저가매수·고가매도)
⚠️ 단 공짜가 아니다:
   ① 조정할 때마다 **거래비용**을 낸다 → 자주 할수록 불리
   ② 한 섹터가 계속 오르면 **일찍 팔아 손해**를 본다 (2025~2026 정보기술이 그랬을 것)
⇒ 그래서 **주기별로 비용 후 성적**을 재야 한다
```

## 재는 것
```
① 섹터 상관     ⚠️ **이게 낮아야 분산이 먹힌다.** 다 같이 움직이면 리밸런싱은 헛수고다
② 리밸런싱 주기  안 함(buy&hold) / 월 / 분기 / 반기 / 연 / 밴드(±5%p 벗어나면)
③ 비중 방식     동일가중 / 역변동성(변동성 큰 섹터에 적게)
④ 대상        코스피200 섹터 8개 / 코스피 크기 3개 / 코스피+코스닥 2개
⑤ 판정        코스피 대비 · 낙폭 · 수익/낙폭 比 · 학습/검증 분리 · 연도별
```
⚠️⚠️ **지수는 배당을 안 담는다(price index).** 실제 ETF는 배당을 받으므로 절대 수익은
   여기 나온 것보다 높다. 다만 **비교(리밸런싱 vs 안 함)에는 영향이 적다.**
⚠️ 편도 비용 0.13%를 **실제로 옮긴 금액에만** 매긴다.
"""
