def _쟀나(조각):
    if not 조각:
        return "✅", ""
    fs = [os.path.basename(f) for f in glob.glob(os.path.join(_LABS, f"*{조각}*"))]
    if not fs:
        return "⬜", ""
    return "✅", sorted(fs)[-1]


def _규모띠():
    """[(라벨, 종목수)] — 오늘 기준"""
    import bisect
    fs = sorted(f for f in os.listdir(os.path.join(_D, "krx-daily")) if f.endswith(".json"))
    if not fs:
        return [], 0
    j = json.load(io.open(os.path.join(_D, "krx-daily", fs[-1]), encoding="utf-8-sig"))
    종 = next(v for v in j.values()
              if isinstance(v, dict) and any(isinstance(x, dict) and x.get("시총") for x in list(v.values())[:3]))
    mc = sorted((x["시총"] / 1e8) for x in 종.values() if x.get("시총"))
    띠 = [(0, 300, "~300억"), (300, 2000, "300~2,000억 (지금)"), (2000, 10000, "2,000억~1조"),
          (10000, 100000, "1조~10조"), (100000, 1000000, "10조~100조"), (1000000, 9e12, "100조 이상")]
    return [(라, bisect.bisect_left(mc, hi) - bisect.bisect_left(mc, lo)) for lo, hi, 라 in 띠], len(fs)


