def 세기(폴더):
    r"""파일 수·이름꼴·**알맹이 건수**를 센다.

    ⚠️⚠️ **2026-09-07 세 번 고쳤다.** 처음엔 위 칸의 `*.json` 만 셌다. 그래서
       krx-extra(하위 폴더 3개 x 649일)와 dart-snap(하위 폴더 3개 x 2,651종목)을
       「비어 있다」로 적었고, consensus 81을 「81일」로 적었다 — 실제로는
       **81달치(202001~202609) 리포트 21,191건**이다.
       ⇒ 하위 폴더까지 내려가고, 리스트 길이를 더해 **속 건수**를 센다
    """
    p = os.path.join(_DATA, 폴더)
    fs = sorted(glob.glob(os.path.join(p, "**", "*.json"), recursive=True))
    if not fs:
        fs = [f for f in sorted(glob.glob(os.path.join(p, "**", "*"),
                                          recursive=True))
              if os.path.isfile(f)]
    이름들 = [os.path.splitext(os.path.basename(f))[0] for f in fs]
    def _날인가(n):
        return len(n) == 8 and n.isdigit() and 1990 <= int(n[:4]) <= 2099

    def _달인가(n):
        return (len(n) == 6 and n.isdigit() and 1990 <= int(n[:4]) <= 2099
                and 1 <= int(n[4:]) <= 12)

    # ⚠️⚠️ **전부 맞아야 한다** (2026-09-07 다섯 번째 고침).
    #    「하나라도 맞으면」으로 했더니 종목코드 005930·950260 이
    #    2005.93·2087.10 같은 **달**로 읽혔다. dart-capital 이
    #    「2007.10~2087.10 · 3,988달」로 나왔다 — 실제로는 종목 3,988개다
    날짜꼴 = sorted(n for n in 이름들 if _날인가(n))
    달꼴 = sorted(n for n in 이름들 if _달인가(n))
    처음, 끝, 꼴 = "", "", "기타"
    if 이름들 and len(날짜꼴) == len(이름들):
        처음, 끝, 꼴 = 날짜꼴[0], 날짜꼴[-1], "날"
    elif 이름들 and len(달꼴) == len(이름들):
        처음, 끝, 꼴 = 달꼴[0], 달꼴[-1], "달"

    # 속 건수 — 파일 몇 개만 열어 평균을 내고 전체로 늘린다
    맛 = fs[:8] + fs[len(fs) // 2:len(fs) // 2 + 4] + fs[-8:]
    합, 본것 = 0, 0
    for f in 맛:
        try:
            d = json.load(io.open(f, encoding="utf-8-sig"))
        except Exception:
            continue
        본것 += 1
        합 += 알맹이(d)
    평균 = (합 / 본것) if 본것 else 0
    속 = int(평균 * len(fs))
    return len(fs), 처음, 끝, 속, 꼴


def 알맹이(d, 깊이=0):
    """이 파일 안에 든 **줄 수** — 리스트면 길이, 딕셔너리면 값들을 더한다"""
    if isinstance(d, list):
        return len(d)
    if isinstance(d, dict):
        가장 = 0
        for v in d.values():
            if isinstance(v, list):
                가장 = max(가장, len(v))
            elif isinstance(v, dict) and 깊이 < 2:
                안 = 알맹이(v, 깊이 + 1)
                가장 = max(가장, 안 if 안 else len(v))
        return 가장
    return 0


def 속길이(폴더, 몇개=6):
    """파일 안에 든 **줄 수**를 잰다 (날짜 축이 아닌 폴더용).

    ⚠️⚠️ **2026-09-07: 이걸 안 해서 크게 틀렸다.**
       yahoo 를 「96건뿐 — 표본 부족」이라고 적었는데, 96은 **심볼 수**고
       심볼마다 6,968일(1998~2026)이 들어 있었다.
       fred 도 「2건」이 아니라 **일별 26,361줄**이다.
       그 바람에 「미국 종목으로는 규칙을 못 만든다」고 말했는데 **틀렸다**
    """
    p = os.path.join(_DATA, 폴더)
    fs = sorted(glob.glob(os.path.join(p, "*.json")))
    가장 = 0
    for f in fs[:몇개] + fs[-몇개:]:
        try:
            d = json.load(io.open(f, encoding="utf-8-sig"))
        except Exception:
            continue
        틀 = [d] if isinstance(d, dict) else []
        for 층 in 틀:
            for v in 층.values():
                if isinstance(v, (dict, list)):
                    가장 = max(가장, len(v))
                    if isinstance(v, dict):
                        for v2 in list(v.values())[:3]:
                            if isinstance(v2, (dict, list)):
                                가장 = max(가장, len(v2))
    return 가장


