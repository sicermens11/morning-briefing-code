def 큰묶음(d, 깊이=0):
    r"""이 파일에 든 **줄 수** — 가장 바깥에서 가장 큰 묶음의 크기.

    ⚠️⚠️ **2026-09-14 고침.** 옛 `알맹이()` 는 값이 딕셔너리면 `len(v)`,
       즉 **필드 수**를 잡았다:
    ```
    contract  {"건수":217, "건": {…217개…}}
              "건" 의 값 하나가 필드 6개짜리 dict  ->  6 을 돌려줬다
    ```
    ⇒ 딕셔너리를 만나면 **그 길이를 먼저** 쓰고, 한 겹만 더 내려가 본다.
       (krx-extra 가 {"기준일", "자료": {키: [줄들]}} 라 한 겹이 더 필요하다)
    """
    if isinstance(d, list):
        return len(d)
    if not isinstance(d, dict):
        return 0
    가장 = 0
    for v in d.values():
        if isinstance(v, (list, dict)):
            가장 = max(가장, len(v))
            if 깊이 < 2:
                가장 = max(가장, 큰묶음(v, 깊이 + 1))
    return 가장


def _날인가(n):
    return len(n) == 8 and n.isdigit() and 1990 <= int(n[:4]) <= 2099


def _달인가(n):
    # ⚠️⚠️ **전부 맞아야 한다** (2026-09-07). 「하나라도 맞으면」으로 했더니
    #    종목코드 005930·950260 이 2005.93·2087.10 같은 **달**로 읽혔다.
    return (len(n) == 6 and n.isdigit() and 1990 <= int(n[:4]) <= 2099
            and 1 <= int(n[4:]) <= 12)


def 한묶음(경로, 다열기=True):
    r"""하위 폴더 **하나**를 센다. 합치지 않는다.

    ⚠️ 옛 판은 하위 폴더를 `**/*.json` 으로 싹 긁어 합쳤다. 그래서
       「649일짜리 3종류」가 「1,947일」이 됐고, krx-extra 를 2년짜리로 오해했다.
    """
    fs = [f for f in sorted(os.listdir(경로))
          if os.path.isfile(os.path.join(경로, f))]
    이름들 = [os.path.splitext(f)[0] for f in fs]
    날 = sorted(n for n in 이름들 if _날인가(n))
    달 = sorted(n for n in 이름들 if _달인가(n))
    꼴, 처음, 끝 = "기타", "", ""
    if 이름들 and len(날) == len(이름들):
        꼴, 처음, 끝 = "날", 날[0], 날[-1]
    elif 이름들 and len(달) == len(이름들):
        꼴, 처음, 끝 = "달", 달[0], 달[-1]

    대상 = fs if 다열기 else (fs[:20] + fs[len(fs) // 2:len(fs) // 2 + 10]
                             + fs[-20:])
    속, 빈, 잰것 = 0, 0, 0
    for f in 대상:
        try:
            d = json.load(io.open(os.path.join(경로, f), encoding="utf-8-sig"))
        except Exception:
            continue
        잰것 += 1
        n = 큰묶음(d)
        속 += n
        if n == 0:
            빈 += 1
    if not 다열기 and 잰것:
        속 = int(속 / 잰것 * len(fs))
        빈 = int(빈 / 잰것 * len(fs))
    return {"파일": len(fs), "꼴": 꼴, "처음": 처음, "끝": 끝,
            "속": 속, "빈": 빈, "어림": not 다열기}


def 규모말(축, v):
    """규모 칸 한 줄 — 전부 실측값이다"""
    if v["꼴"] == "날":
        말 = f"{v['처음'][:4]}~{v['끝'][:4]} · {v['파일']:,}일"
    elif v["꼴"] == "달":
        말 = (f"{v['처음'][:4]}.{v['처음'][4:]}~{v['끝'][:4]}.{v['끝'][4:]}"
              f" · {v['파일']:,}달")
    else:
        말 = f"{축} {v['파일']:,}개"
    if v["속"]:
        말 += f" · 속 {v['속']:,}건"
        if v["어림"]:
            말 += "(어림)"
    if v["빈"]:
        말 += f" · 빈 {v['빈']:,}"
    return 말


def 세기(이름, 빨리=False):
    """폴더 하나 → 줄 여럿 (하위 폴더가 있으면 **하위마다 한 줄**)"""
    p = os.path.join(_DATA, 이름)
    하위 = [n for n in sorted(os.listdir(p))
            if os.path.isdir(os.path.join(p, n))]
    위파일 = [f for f in os.listdir(p) if os.path.isfile(os.path.join(p, f))]

    def _열까(경로):
        if 빨리:
            return False
        n = len([f for f in os.listdir(경로)
                 if os.path.isfile(os.path.join(경로, f))])
        return n <= 6000

    줄들 = []
    if 위파일:
        줄들.append(("", 한묶음(p, _열까(p))))
    for h in 하위:
        hp = os.path.join(p, h)
        if any(os.path.isdir(os.path.join(hp, x)) for x in os.listdir(hp)):
            continue                      # 두 층까지만 본다 (snapshots/날짜/… )
        줄들.append((h, 한묶음(hp, _열까(hp))))
    # snapshots 처럼 하위가 수십 개면 한 줄로 접는다
    if len(줄들) > 6:
        합 = {"파일": sum(v["파일"] for _, v in 줄들), "꼴": "기타",
              "처음": "", "끝": "", "속": sum(v["속"] for _, v in 줄들),
              "빈": sum(v["빈"] for _, v in 줄들),
              "어림": any(v["어림"] for _, v in 줄들)}
        줄들 = [(f"({len(줄들)}묶음)", 합)]
    return 줄들


