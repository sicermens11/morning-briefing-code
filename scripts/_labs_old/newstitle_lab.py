#!/usr/bin/env python3
r"""
newstitle_lab.py — **뉴스 제목이 결과를 가르나** (2026-09-03 · 79차)

⚠️⚠️ **73차에서 못 잰 부분을 잰다.**
```
73차에서 잰 것   **거래대금 배수** = 「관심의 **양**」
                -> 급증할수록 나빴다 (10배 이상 -1.49% · 승률 41.3%)
                -> 「조용한 게 낫다」가 결론이었다
73차에서 **못** 잰 것  **내용이 호재냐 악재냐**
                -> 제목이 있어야 가른다. 이제 받았다 (네이버 금융 종목뉴스 23종목)
```

## ⚠️⚠️ 이 시험의 한계를 먼저 말한다
```
표본이 **30건**뿐이다 (최근 12개월 신호). 통계로 판정할 수 없다.
뉴스도 **1년치**만 받힌다 (네이버 한계) — 16.7년 백테스트는 불가능하다.
⇒ 이건 **판정이 아니라 정찰**이다. 방향이 보이면 그때 넓힌다.
```

## 재는 것
```
A 매수 직전 N일 안에 뉴스가 **있었나 없었나**
B 있었다면 제목이 **호재말 · 악재말** 중 어느 쪽인가
C 뉴스 **건수**가 많을수록 어떤가 (73차 거래대금과 같은 방향인가)
D 실제 제목을 눈으로 본다 — 자동 분류가 맞는지 확인
```
⚠️ 제목 분류는 **단어 목록**으로 한다. 완벽하지 않다 — D에서 눈으로 확인한다.
"""
import glob
import io
import json
import os
import re
import statistics as st
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

_BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_NEWS = os.path.join(_BASE, "data", "news")
# ⚠️ 하루 2종목 상한을 푼 `_all` 판을 쓴다 — 표본이 30건 -> 134건이 된다.
#   ⚠️⚠️ **상한을 푼 것은 「표본을 넓히려고」이지 매매 규칙을 바꾼 게 아니다.**
#      실제 매매는 77차 규칙(하루 2종목)을 그대로 쓴다
_PICK = os.path.join(_BASE, "data", "_labs", "2026-09-03_picknow78_all.txt")
if not os.path.exists(_PICK):
    _PICK = os.path.join(_BASE, "data", "_labs", "2026-09-03_picknow78.txt")

# ⚠️ 단어 목록은 **완벽하지 않다.** D에서 눈으로 확인한다
# ⚠️⚠️ **2026-09-03 1차 확인 후 보강.** AP위성의 "5억 규모 자사주 처분 결정"이
#   **중립**으로 분류됐다. 29차에서 자사주 처분은 **t=-7.7의 강한 악재**였는데
#   목록에 없어서 놓쳤다. 29·55차에서 확인한 공시 효과를 그대로 반영한다:
#     호재  자기주식 취득 (t=+6.8)
#     악재  유상증자·최대주주변경·신주인수권·전환사채·소송·합병·감자·**자기주식 처분**
호재말 = ("수주", "계약 체결", "공급계약", "신고가", "급등", "상한가",
          "흑자전환", "호실적", "사상 최대", "성장", "확대", "진출", "출시",
          "승인", "허가", "특허", "선정", "채택", "돌파", "회복", "개선",
          "협력", "제휴", "투자유치", "수출", "목표주가 상향", "매수 의견",
          "자사주 취득", "자기주식 취득", "자사주 매입", "무상증자")
악재말 = ("급락", "하한가", "적자", "손실", "감소", "부진", "하향", "철회",
          "취소", "소송", "횡령", "배임", "조사", "제재", "경고",
          "구조조정", "감원", "상장폐지", "거래정지", "불성실",
          "목표주가 하향", "실적 악화", "어닝쇼크", "실적 쇼크",
          # 29·55차에서 확인한 악재 공시
          "유상증자", "최대주주 변경", "최대주주변경", "신주인수권",
          "전환사채", "감자", "자사주 처분", "자기주식 처분", "블록딜",
          "오버행", "지분 매각", "보호예수 해제")


def 분류(제목):
    h = sum(1 for w in 호재말 if w in 제목)
    b = sum(1 for w in 악재말 if w in 제목)
    if h > b:
        return "호재"
    if b > h:
        return "악재"
    return "중립"


def main():
    if not os.path.exists(_PICK):
        print("  78차 결과가 없다. pick_now.py를 먼저 돌려야 한다")
        return 1
    뽑 = []
    for line in io.open(_PICK, encoding="utf-8"):
        m = re.match(r"\s+(\d{8})\s+(\d{6})\s+(\S*)\s+([\d,]+)\s+([-+][\d.]+)%"
                     r"\s+([-+][\d.]+)%\s+([\d,]+)억\s+(\S+)\s+([-+][\d.]+)%"
                     r"\s+(\d+)\s+(\S+)", line)
        if m:
            뽑.append({"날": m.group(1), "code": m.group(2), "이름": m.group(3),
                       "결과": float(m.group(9)), "며칠": int(m.group(10)),
                       "상태": m.group(11)})
    if not 뽑:
        print("  78차 표를 못 읽었다")
        return 1
    print(f"  신호 {len(뽑)}건 · 종목 {len({x['code'] for x in 뽑})}개\n")

    뉴스 = {}
    for f in glob.glob(os.path.join(_NEWS, "*.json")):
        try:
            d = json.load(io.open(f, encoding="utf-8-sig"))
        except Exception:
            continue
        뉴스[d["종목"]] = d.get("뉴스") or []
    print(f"  뉴스를 받은 종목 {len(뉴스)}개 · "
          f"총 {sum(len(v) for v in 뉴스.values()):,}건\n")

    def 앞뉴스(code, 날, 며칠=5):
        a = 뉴스.get(code) or []
        # 매수일 **이전** N일 (매수일 당일 아침 뉴스는 이미 갭에 반영됐다고 본다)
        import datetime as dt
        d1 = dt.datetime.strptime(날, "%Y%m%d")
        시작 = (d1 - dt.timedelta(days=며칠)).strftime("%Y%m%d")
        return [x for x in a if 시작 <= x["날짜"] < 날]

    for x in 뽑:
        n = 앞뉴스(x["code"], x["날"])
        x["뉴스수"] = len(n)
        cls = [분류(z["제목"]) for z in n]
        x["호재"] = sum(1 for c in cls if c == "호재")
        x["악재"] = sum(1 for c in cls if c == "악재")
        x["성격"] = ("없음" if not n else
                     "호재" if x["호재"] > x["악재"] else
                     "악재" if x["악재"] > x["호재"] else "중립")
        x["제목들"] = [z["제목"] for z in n]

    def 재기(a, 라):
        if len(a) < 3:
            print(f"    {라:<26}{len(a):>4}건  — 표본 부족")
            return
        v = [x["결과"] for x in a]
        승 = sum(1 for z in v if z > 0) / len(v) * 100
        목표 = sum(1 for x in a if x["상태"] == "목표달성")
        print(f"    {라:<26}{len(a):>4}건{st.mean(v):>+9.2f}%{승:>7.1f}%"
              f"{목표/len(a)*100:>9.0f}%{st.mean([x['며칠'] for x in a]):>7.1f}일")

    print("  ══ A 매수 직전 5일 안에 **뉴스가 있었나** ══")
    print("     ⚠️ 표본 30건이다. **판정이 아니라 정찰이다**")
    print(f"    {'구분':<26}{'건수':>6}{'평균':>9}{'승률':>8}{'목표달성':>9}{'보유':>8}")
    재기(뽑, "전체")
    재기([x for x in 뽑 if x["뉴스수"] == 0], "뉴스 **없음**")
    재기([x for x in 뽑 if x["뉴스수"] > 0], "뉴스 있음")

    print("\n  ══ B 제목이 **호재냐 악재냐** ══")
    print(f"    {'구분':<26}{'건수':>6}{'평균':>9}{'승률':>8}{'목표달성':>9}{'보유':>8}")
    for 성 in ("없음", "중립", "호재", "악재"):
        재기([x for x in 뽑 if x["성격"] == 성], f"직전 5일 {성}")

    print("\n  ══ C 뉴스 **건수**가 많을수록 (73차 거래대금과 같은 방향인가) ══")
    print(f"    {'구분':<26}{'건수':>6}{'평균':>9}{'승률':>8}{'목표달성':>9}{'보유':>8}")
    재기([x for x in 뽑 if x["뉴스수"] == 0], "0건")
    재기([x for x in 뽑 if x["뉴스수"] in (1, 2)], "1~2건")
    재기([x for x in 뽑 if x["뉴스수"] >= 3], "3건 이상")

    print("\n  ══ D **실제 제목** — 자동 분류가 맞는지 눈으로 본다 ══")
    for x in sorted(뽑, key=lambda z: -z["결과"])[:6]:
        print(f"    ⭐ {x['날']} {x['이름'][:10]:<11} {x['결과']:+.1f}% "
              f"({x['며칠']}일) · 직전 뉴스 {x['뉴스수']}건 [{x['성격']}]")
        for t in x["제목들"][:2]:
            print(f"        · {t[:58]}")
    print()
    for x in sorted(뽑, key=lambda z: z["결과"])[:4]:
        print(f"    ❌ {x['날']} {x['이름'][:10]:<11} {x['결과']:+.1f}% "
              f"({x['며칠']}일) · 직전 뉴스 {x['뉴스수']}건 [{x['성격']}]")
        for t in x["제목들"][:2]:
            print(f"        · {t[:58]}")

    print("\n  읽는 법")
    print("    - ⚠️⚠️ **표본 30건이다. 통계로 판정할 수 없다.** 방향만 본다")
    print("    - 73차에서 「관심의 **양**」은 많을수록 나빴다.")
    print("       여기서 「**내용**」이 갈리는지가 새로 보는 것이다")
    print("    - D에서 자동 분류가 엉뚱하면 **단어 목록을 고쳐야** 한다")
    return 0


if __name__ == "__main__":
    sys.exit(main())
