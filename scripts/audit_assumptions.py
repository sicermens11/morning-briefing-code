# 실제로 흔든 판이 있나 — 결과 파일에서 옵 이름을 찾는다
_글 = {}
for f in glob.glob(os.path.join(_랩, "*.txt")):
    try:
        _글[os.path.basename(f)] = io.open(f, encoding="utf-8", errors="replace").read()
    except OSError:
        pass


def _흔든판(손잡이):
    if not 손잡이:
        return []
    말들 = [z.strip() for z in 손잡이.split("·")]
    벌 = []
    for _f, _g in _글.items():
        if any(w and w in _g for w in 말들):
            벌.append(_f[:30])
    return sorted(벌)


안흔듦, 흔듦 = [], []
for 이름, 값, 손, 뜻 in 가정:
    판 = _흔든판(손)
    (흔듦 if 판 else 안흔듦).append((이름, 값, 손, 뜻, 판))

