#!/usr/bin/env python3
r"""
sim_brief.py — **브리핑 대로 샀을 때 (사용자 규칙)** (2026-09-02 · 49차)

⚠️⚠️ **사용자가 정한 규칙 그대로 돌린다.**
   *"최우선매수, 매수권고가 나오면 10만원씩 매수, 1주당 10만원 이상인 종목은 1주 매수"*
   ⚠️ 이건 **시뮬레이션**이다(가정을 세우고 굴리는 것). 테스트(과거 사실 확인)와 구분한다.

## 지금까지 내가 돌린 시뮬과 뭐가 다른가
```
내가 돌린 것(final_sim 계열 8개)   전 자산 100%를 굴리며 **자리 30개를 채우는 펀드 운용**
이것                            **브리핑에 뜬 종목을 10만원씩 사는 개인**
⇒ 가정이 사용자 상황과 맞다. 앞의 것은 안 맞아서 오늘 셋을 잘못 기각했다
```

## 신호 (47차에서 모든 관문 통과)
```
볼린저 하단 이탈 + 갭 −2%↓ + 최근 20일 −10%↓ · 소형
  절대 +7.90% · 승률 66.0% · 연 1,139건 · **16해 중 15해 +** · 종목 편중 없음(상위10 1.8%)
  매수 **다음날 시가** · 매도 **D+40**(최적) · **손절 없음**(걸면 최악이 더 나빠진다)
```

## 자금 제약이 핵심이다
```
하루 4.6건 × 10만원 = 하루 46만원. 1년이면 **1.1억**이 필요하다
⇒ 실제로는 **가진 돈 안에서만** 산다. 팔아서 회수한 돈으로 다시 산다
⇒ 초기자금 **500만 / 1,000만 / 3,000만 / 무제한**을 견준다
```
⚠️ 하루에 여러 종목이 뜨면 **거래대금 큰 것부터** 산다(살 수 있는 것 우선).
⚠️ 왕복비용 0.26%. 수정주가. 16.7년.
"""
import glob
import io
import json
import os
import statistics as st
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import omni_lab as O  # noqa: E402

_비용 = 0.0026
_보유 = 40
_한종목 = 100_000       # 종목당 10만원


def _주가():
    원 = {}
    for f in sorted(glob.glob(os.path.join(O._DATA, "krx-daily", "*.json"))):
        d = json.load(io.open(f, encoding="utf-8-sig"))
        하루 = {}
        for c, v in d["종목"].items():
            try:
                종 = float(v["종가"])
                if 종 <= 0:
                    continue
                시 = float(v.get("시가") or 0) or 종
            except (TypeError, ValueError, KeyError):
                continue
            등 = v.get("등락률")
            try:
                등 = float(등) if 등 not in (None, "") else None
            except (TypeError, ValueError):
                등 = None
            if 등 is not None and abs(등) > 31.0:
                등 = None
            try:
                시총 = float(v.get("시총") or 0)
                대금 = float(v.get("거래대금") or 0)
            except (TypeError, ValueError):
                시총 = 대금 = 0.0
            하루[c] = (종, 시, 등, 시총, 대금)
        원[d["기준일"]] = 하루
    날 = sorted(원)
    앞원, 앞수, 배표 = {}, {}, {}
    out = {}
    for d in 날:
        하루 = {}
        for c, (종, 시, 등, 시총, 대금) in 원[d].items():
            p, s = 앞원.get(c), 앞수.get(c)
            if p is None or s is None:
                수 = 종
            elif 등 is not None:
                수 = s * (1 + 등 / 100.0)
            else:
                r = 종 / p - 1 if p > 0 else 0.0
                수 = s * (1 + (0.0 if abs(r) > 0.32 else r))
            if 수 <= 0:
                수 = s if s and s > 0 else 종
            배 = 수 / 종 if 종 else 1.0
            배표[c] = 배
            앞원[c], 앞수[c] = 종, 수
            # ⚠️ **실제 주문은 원본 가격으로 한다** — 10만원으로 몇 주 살지는 원본 가격이 정한다
            하루[c] = (수, 시 * 배, 시총, 대금, 종, 시)   # (수정종가, 수정시가, 시총, 대금, 원본종가, 원본시가)
        out[d] = 하루
    return out


def main():
    print("  자료 읽는 중...", flush=True)
    주가 = _주가()
    날 = sorted(주가)
    지수, 기본 = O._지수(), O._기본()
    종계, 자리 = {}, {}
    for d in 날:
        for c, v in 주가[d].items():
            종계.setdefault(c, []).append(v[0])
            자리.setdefault(c, {})[d] = len(종계[c]) - 1
    print(f"  거래일 {len(날):,}", flush=True)

    # 브리핑 목록: 날 -> [(거래대금, code)]  (그날 아침 브리핑에 뜬 종목)
    브리핑 = {}
    총사건 = 0
    for i, d1 in enumerate(날):
        if i < 260 or i + 1 + _보유 >= len(날):
            continue
        묶 = []
        for code, v in 주가[d1].items():
            c1, _시, 시총, 대금, _원종, _원시 = v
            if 시총 < O._MIN_MC or 대금 < O._MIN_AMT or 시총 >= 3e11:
                continue
            bb = 기본.get(code) or {}
            부 = str(bb.get("업종") or "")
            if (("관리종목" in 부) or ("SPAC" in 부)
                    or (bb.get("증권구분") not in (None, "주권"))):
                continue
            k = (자리.get(code) or {}).get(d1)
            if k is None or k < 250:
                continue
            sq = 종계[code]
            s20 = st.mean(sq[k - 19:k + 1])
            sd = st.pstdev(sq[k - 19:k + 1]) or 1e-9
            if (c1 - s20) / (2 * sd) > -1.0:
                continue
            if k < 20 or sq[k - 20] <= 0 or (c1 / sq[k - 20] - 1) * 100 > -10:
                continue
            나 = 주가[날[i + 1]].get(code)
            if not 나 or 나[1] <= 0:
                continue
            if (나[1] / c1 - 1) * 100 > -2:     # ⚠️ 갭은 다음날 아침에 확인한다
                continue
            묶.append((대금, code))
            총사건 += 1
        if 묶:
            묶.sort(reverse=True)               # 거래대금 큰 것부터
            브리핑[i] = 묶
    print(f"  브리핑에 뜬 종목 {총사건:,}건 · 뜬 날 {len(브리핑):,}일 "
          f"· 연 {총사건/(len(날)/245):.0f}건", flush=True)

    def 주수계산(방식, 단가):
        """⚠️ 사용자 지적(2026-09-02): *"종목당 10만원씩 말고 무조건 1주 이상으로 하자"*
        두 해석이 가능해 **둘 다 돌린다**:
          '10만원'  10만원어치 사되 주가가 10만원을 넘으면 1주  ← 원래 규칙
          '1주'     종목당 그냥 1주씩
        추가로 5만원·20만원도 견줘 **금액 크기가 성적에 영향을 주는지** 본다."""
        if 방식 == "1주":
            return 1
        금 = {"5만원": 50_000, "10만원": 100_000, "20만원": 200_000}[방식]
        return max(1, int(금 // 단가))

    def 굴리기(초기, 하루최대, 방식="10만원", 보유일=_보유):
        현금 = float(초기)
        보유 = []       # (청산idx, code, 매수단가(원본), 주수, 산금액)
        곡선 = []
        이긴 = 진 = 0
        산건 = 0
        못산 = 0
        for i in range(260, len(날)):
            s1 = 주가[날[i]]
            # ── 청산 (그날 시가에 판다) ──
            남 = []
            for (끝i, code, 단가, 주수, 산금) in 보유:
                if i >= 끝i:
                    v = s1.get(code)
                    팔단가 = (v[5] if v else 단가)      # 원본 시가
                    받 = 주수 * 팔단가 * (1 - _비용 / 2)
                    현금 += 받
                    이긴 += 1 if 받 > 산금 else 0
                    진 += 1 if 받 <= 산금 else 0
                else:
                    남.append((끝i, code, 단가, 주수, 산금))
            보유 = 남
            # ── 매수 (전날 브리핑 → 오늘 아침 시가) ──
            앞i = i - 1
            if 앞i in 브리핑:
                든 = {c for (_, c, _, _, _) in 보유}
                산오늘 = 0
                for _대금, code in 브리핑[앞i]:
                    if 산오늘 >= 하루최대:
                        break
                    if code in 든:
                        continue
                    v = s1.get(code)
                    if not v or v[5] <= 0:
                        continue
                    단가 = v[5]                       # ⚠️ 원본 시가로 주문한다
                    주수 = 주수계산(방식, 단가)
                    금액 = 주수 * 단가 * (1 + _비용 / 2)
                    if 금액 > 현금:
                        못산 += 1
                        continue
                    현금 -= 금액
                    보유.append((i + 보유일, code, 단가, 주수, 금액))
                    든.add(code)
                    산건 += 1
                    산오늘 += 1
            평가 = 0.0
            for (_, code, 단가, 주수, _금) in 보유:
                v = s1.get(code)
                평가 += 주수 * (v[4] if v else 단가)   # 원본 종가로 평가
            곡선.append(현금 + 평가)
        # 마지막 청산
        s1 = 주가[날[-1]]
        for (_, code, 단가, 주수, _금) in 보유:
            v = s1.get(code)
            현금 += 주수 * ((v[4] if v else 단가)) * (1 - _비용 / 2)
        최고, 낙 = 곡선[0] if 곡선 else 1, 0.0
        for x in 곡선:
            최고 = max(최고, x)
            낙 = min(낙, x / 최고 - 1)
        거 = 이긴 + 진
        return 현금, 낙 * 100, 거, (이긴 / 거 * 100 if 거 else 0), 산건, 못산, 곡선

    년 = (len(날) - 260) / 245
    있 = [d for d in 날[260:] if 지수.get(d)]
    배 = 지수[있[-1]]["KOSPI"] / 지수[있[0]]["KOSPI"]
    지연 = (배 ** (1 / 년) - 1) * 100
    print(f"\n  ══ ① **매수 단위** 비교 (초기 1,000만 · 하루 3개 · 매도 D+{_보유}) ══")
    print(f"     기간 {날[260][:4]}~{날[-1][:4]} ({년:.1f}년) · 코스피 연 {지연:+.1f}%")
    print(f"    {'매수 단위':<10}{'최종자산':>14}{'배수':>8}{'연환산':>9}"
          f"{'낙폭':>8}{'매수':>7}{'승률':>7}{'못산':>7}")
    for 방식 in ("1주", "5만원", "10만원", "20만원"):
        자산, 낙, 거, 승, 산, 못, _ = 굴리기(10_000_000, 3, 방식)
        배수 = 자산 / 10_000_000
        연 = (배수 ** (1 / 년) - 1) * 100 if 배수 > 0 else -100
        표 = "⭐" if 연 > 지연 else "  "
        print(f"    {방식:<10}{자산:>13,.0f}원{배수:>8.2f}{연:>8.1f}%"
              f"{낙:>7.1f}%{산:>7,}{승:>6.0f}%{못:>7,}{표}")

    print(f"\n  ══ ② **매도 시점** 비교 (초기 1,000만 · 하루 3개 · 10만원) ══")
    print(f"    {'매도':<10}{'최종자산':>14}{'배수':>8}{'연환산':>9}"
          f"{'낙폭':>8}{'매수':>7}{'승률':>7}")
    for 보유일 in (10, 20, 40, 60):
        자산, 낙, 거, 승, 산, 못, _ = 굴리기(10_000_000, 3, "10만원", 보유일)
        배수 = 자산 / 10_000_000
        연 = (배수 ** (1 / 년) - 1) * 100 if 배수 > 0 else -100
        표 = "⭐" if 연 > 지연 else "  "
        print(f"    {'D+'+str(보유일):<10}{자산:>13,.0f}원{배수:>8.2f}{연:>8.1f}%"
              f"{낙:>7.1f}%{산:>7,}{승:>6.0f}%{표}")

    print(f"\n  ══ ③ **초기자금 × 하루 최대 종목 수** (10만원 · D+{_보유}) ══")
    print(f"    {'초기자금':<12}{'하루최대':<9}{'최종자산':>14}{'배수':>8}{'연환산':>9}"
          f"{'낙폭':>8}{'매수':>7}{'승률':>7}{'못산':>7}")
    최선 = None
    for 초기 in (5_000_000, 10_000_000, 30_000_000, 100_000_000):
        for 하루최대 in (3, 10):
            자산, 낙, 거, 승, 산, 못, 곡선 = 굴리기(초기, 하루최대)
            배수 = 자산 / 초기
            연 = (배수 ** (1 / 년) - 1) * 100 if 배수 > 0 else -100
            표 = "⭐" if 연 > 지연 else "  "
            print(f"    {초기//10000:>9,}만{하루최대:>7}개{자산:>13,.0f}원"
                  f"{배수:>8.2f}{연:>8.1f}%{낙:>7.1f}%{산:>7,}{승:>6.0f}%{못:>7,}{표}")
            if 최선 is None or 연 > 최선[0]:
                최선 = (연, 초기, 하루최대, 곡선)

    # 연도별
    print(f"\n  ══ 연도별 (초기 {최선[1]//10000:,}만원 · 하루 최대 {최선[2]}개) ══")
    _, _, _, _, _, _, 곡선 = 굴리기(최선[1], 최선[2])
    해별 = {}
    앞v = None
    for j, d in enumerate(날[260:260 + len(곡선)]):
        y = d[:4]
        if y not in 해별:
            해별[y] = [앞v if 앞v is not None else 곡선[j], 곡선[j]]
        해별[y][1] = 곡선[j]
        앞v = 곡선[j]
    지해, 앞x = {}, None
    for d in 날[260:]:
        x = (지수.get(d) or {}).get("KOSPI")
        if not x:
            continue
        y = d[:4]
        if y not in 지해:
            지해[y] = [앞x if 앞x else x, x]
        지해[y][1] = x
        앞x = x
    print(f"    {'해':<7}{'자산':>14}{'수익률':>10}{'코스피':>10}{'차이':>10}")
    플, 전 = 0, 0
    for y in sorted(해별):
        a0, a1 = 해별[y]
        수 = (a1 / a0 - 1) * 100 if a0 else 0
        지 = ((지해[y][1] / 지해[y][0] - 1) * 100) if y in 지해 and 지해[y][0] else 0
        전 += 1
        플 += 1 if 수 > 0 else 0
        표 = "⭐" if 수 > 지 else ("  " if 수 > 0 else "❌")
        print(f"    {y:<7}{a1:>13,.0f}원{수:>+9.1f}%{지:>+9.1f}%{수-지:>+9.1f}%{표}")
    print(f"    ⇒ **{전}해 중 {플}해 수익 ({플/전*100:.0f}%)**")

    print("\n  읽는 법")
    print("    - **초기자금이 적으면 못 사는 게 많아진다**('못산' 열). 그만큼 기회를 놓친다")
    print("    - '하루최대'는 하루에 몇 종목까지 살지다. 3개면 하루 30만원이 든다")
    print("    - ⚠️ 이건 **시뮬레이션**이다. 가정: 브리핑에 뜬 것을 **전부** 산다,")
    print("      호가는 무시한다, 세금은 왕복비용 0.26%에 포함한 것으로 본다")
    return 0


if __name__ == "__main__":
    sys.exit(main())
