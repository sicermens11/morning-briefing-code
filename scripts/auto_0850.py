#!/usr/bin/env python3
r"""
auto_0850.py — **08:50 예상체결가를 자동으로 받는다** (2026-09-10 밤 신설)

## 왜 만드나 — 두 문제를 한꺼번에 푼다
```
① **후보가 적은 날은 구조적으로 못 산다** (242차 · 사용자 지적)
   상대갭 = 그 종목 갭 - **후보들의 중앙갭**
   후보 1개 -> 중앙값 = 그 종목 갭 -> 상대갭 **항상 0** -> 못 산다
   후보 1개 이하인 날이 **441/1,794일 (24.6%)**

② **사람이 손으로 넣어야 한다**
   지금은 후보 8개를 화면에서 보고 `--동시호가 "052460=4550,..."` 로 친다
   -> 40개는 무리다. 그래서 8개만 넣었고, 중앙값이 **불안정**했다
```

## 242·246차에서 확인한 것
```
㉡ 전 종목 중앙갭    끝 자산 **2.6배** · 걷기검증 앞 +124% 뒤 +23%
                   그런데 **08:50 에 못 구한다** (전 종목 예상체결가를 볼 수 없다)
㉣ ETF(지수) 갭     구할 수 있지만 전 종목 중앙갭과 **상관 -0.031** — 무관하다
                   (KODEX 200 은 **대형주 200개**, 우리 후보는 **소형주**다)
⇒ 둘 다 못 쓴다
```

## 그래서 — **후보 40개를 자동으로 받는다**
```
네이버 실시간 API 가 동시호가 중 **예상체결가**를 준다 (`check_entry.fetch_quote`)
  polling.finance.naver.com/api/realtime/domestic/stock/{code}
40개면 중앙값이 훨씬 안정된다. 후보가 1개인 날에도 **40개를 다 받아** 중앙값을 낸다
⚠️ 후보가 1개면 그 1개만 받으니 여전히 상대갭 0 이다 ->
   **후보 밖 종목도 같이 받아** 중앙값을 낸다 (아래 `_시장표본`)
```

## ⚠️ 안 지킨 것
```
· KRX 웹 포털은 **안 두드린다** — 네이버 API 만 쓴다 (이미 쓰던 것)
· 08:30~09:00 이 아니면 **경고**하고 기록하지 않는다
```

쓰는 법:
    python scripts\auto_0850.py            # 받아서 기록까지
    python scripts\auto_0850.py --확인      # 받아만 보고 기록 안 함
"""
import datetime as dt
import io
import json
import os
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from check_entry import fetch_quote  # noqa: E402

_BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOG = os.path.join(_BASE, "data", "forward-log.jsonl")

# ⭐ **시장 표본** — 후보가 적은 날에도 중앙갭을 내려고 같이 받는다.
#    코스피·코스닥에 고루 퍼진 **중소형주** 30개 (대형주는 우리 후보와 성격이 다르다)
#    ⚠️ 246차: KODEX 200 갭은 전 종목 중앙갭과 **상관 -0.031** 이었다
_시장표본 = [
    "005930", "000660", "035420", "051910", "006400", "035720", "207940",
    "068270", "005380", "000270", "012330", "066570", "003550", "015760",
    "017670", "030200", "032640", "090430", "097950", "271560",
    "086520", "091990", "196170", "240810", "058470", "214150", "222080",
    "095700", "084370", "078600",
]


def 찍기(s):
    print(s, flush=True)


def main():
    확인만 = "--확인" in sys.argv
    이제 = dt.datetime.now()
    때 = 이제.strftime("%H:%M")
    if not 확인만 and not ("08:30" <= 때 <= "09:00"):
        찍기(f"  ⚠️⚠️ **지금은 동시호가 시간이 아니다** (지금 {때}).")
        찍기("     08:30~09:00 에만 예상체결가가 나온다.")
        찍기("     그 밖의 시간 값은 **예상체결가가 아니라서** 기록하면 안 된다")
        찍기("     받아만 보려면 `--확인` 을 붙여라")
        return 1

    if not os.path.exists(LOG):
        찍기("  ⚠️ forward-log 가 없다. record_pick 을 먼저 돌려라")
        return 1
    줄들 = [json.loads(x) for x in io.open(LOG, encoding="utf-8") if x.strip()]
    if not 줄들:
        찍기("  ⚠️ 기록이 비어 있다")
        return 1
    끝 = 줄들[-1]
    후보 = 끝.get("후보") or []
    if not 후보:
        찍기("  오늘 후보가 없다 — 받을 것이 없다")
        return 0

    코드들 = [x["종목코드"] for x in 후보]
    찍기(f"  후보 **{len(코드들)}개** + 시장 표본 {len(_시장표본)}개를 받는다")
    받 = {}
    실패 = []
    for i, c in enumerate(코드들 + [z for z in _시장표본 if z not in 코드들], 1):
        try:
            q = fetch_quote(c)
            if q.get("now") and q.get("prev_close"):
                받[c] = {"예상": q["now"], "전일종가": q["prev_close"],
                         "이름": q.get("name") or ""}
        except Exception as e:  # noqa: BLE001
            실패.append(f"{c}({type(e).__name__})")
        time.sleep(0.12)
        if i % 20 == 0:
            찍기(f"    {i}개…")
    찍기(f"  받음 **{len(받)}개** · 실패 {len(실패)}")
    if 실패:
        찍기(f"    실패: {', '.join(실패[:8])}")

    # ── 중앙갭: **받은 것 전부**로 낸다 (후보가 1개여도 표본이 30개는 된다) ──
    갭들 = []
    for c, v in 받.items():
        if v["전일종가"] > 0:
            갭들.append((v["예상"] / v["전일종가"] - 1) * 100)
    if len(갭들) < 10:
        찍기("  ⚠️ 표본이 너무 적다 — 중앙갭을 못 낸다")
        return 1
    갭들.sort()
    중 = 갭들[len(갭들) // 2]
    찍기(f"\n  **시장 중앙갭 {중:+.2f}%** (표본 {len(갭들)}개)")

    찍기(f"\n  {'종목':<14}{'전일종가':>10}{'예상시가':>10}{'갭':>8}{'상대갭':>9}")
    이름표 = {x["종목코드"]: x for x in 후보}
    for c in 코드들:
        v = 받.get(c)
        if not v:
            continue
        갭 = (v["예상"] / v["전일종가"] - 1) * 100
        찍기(f"  {(v['이름'] or 이름표.get(c, {}).get('이름', ''))[:12]:<14}"
             f"{v['전일종가']:>9,.0f}{v['예상']:>10,.0f}"
             f"{갭:>+7.2f}%{갭-중:>+8.2f}p")

    if 확인만:
        찍기("\n  --확인 이라 기록하지 않았다")
        return 0

    # ── 기록 ──
    동 = 끝.setdefault("동시호가", {})
    # ⚠️⚠️ 2026-09-16 발견: 예약이 08:50·55·09:00·09:05 네 번 도는데 **09:00 회차가 시가를 「예상시가」로 덮어썼다**
    #    (오늘 잰시각 09:00:02 · gap_error 표에 +0.00% 줄들). 09:00 부터는 예상이 아니라 시가다 — 기록하지 않는다.
    #    그리고 이미 08:55 이후 값이 있으면 덮지 않는다 (판정 시각 값이 남아야 오차를 잰다)
    if 이제.strftime("%H:%M") >= "09:00":
        찍기("  ⚠️ 09:00 이후 — 예상체결가가 아니라 시가다. **기록하지 않는다**")
        return 0
    _잰 = str(동.get("잰시각") or "")
    if _잰[:10] == 이제.strftime("%Y-%m-%d") and _잰[11:16] >= "08:55":
        찍기(f"  오늘 {_잰[11:16]} 값이 이미 있다 — 덮지 않는다")
        return 0
    동["자동"] = {c: {"예상시가": v["예상"], "전일종가": v["전일종가"],
                     "이름": v["이름"]} for c, v in 받.items()}
    동["시장중앙갭"] = round(중, 3)
    동["표본수"] = len(갭들)
    동["잰시각"] = 이제.strftime("%Y-%m-%d %H:%M:%S")
    with io.open(LOG, "w", encoding="utf-8") as f:
        for r in 줄들:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    찍기(f"\n  ✅ 기록했다 — 표본 {len(갭들)}개 · 중앙갭 {중:+.2f}%")
    찍기("     이제 `record_pick.py --동시호가` 를 손으로 칠 필요가 없다")
    return 0


if __name__ == "__main__":
    sys.exit(main())
