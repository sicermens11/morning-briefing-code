#!/usr/bin/env python3
r"""
multi_lab.py — **여러 규칙을 한 계좌로** (2026-10-01)

## 사용자
「재료는 AND여도 규칙은 OR가 맞는 것 같은데」 · 「여러 규칙을 실전에서 시험을 통과해야하고, 신호가 강한 순서,
 확율이 높은 순서대로 보여줘야 해」 · 「계좌 전체의 하루 최대 종목 수는 개수별로 어떤 영향이 있는지 알고 싶어.
 넣되 표에 ⚠️를 붙이는 걸로 진행하자」 · 기준 docs/목표와_규칙_기준.md

## 무엇을 하나
· 재료 — own_lab(OWN_EXPORT) 이 낸 무리 규칙 20개의 「그날 후보」(data/_labs/multi_cand_own.jsonl)
         + gate7(ONLY=MULTIDUMP) 이 낸 실전 규칙의 「그날 후보」(multi_cand_live.jsonl)
· 계좌 — 한 계좌 · 시드 500만 · 비중 20% · 거래대금 1% 한도 · 현금 연 2.5% · **들고 있는 종목은 전날 종가로 평가**
         (own_lab 시뮬과 같은 셈 — 혼자 돌리면 own_lab ⑨ 「뒤 2019~」 숫자가 그대로 나와야 한다 · ① 대조)
· 하루 순서 — 규칙을 **신호 세기(앞 기간 ~2018 그 규칙 거래의 이김%) 순**으로 줄 세워
         규칙마다 제 자리만큼 뽑고(무리 규칙은 들고 있는 종목 건너뜀 · 실전 규칙은 또 사기 허용 = 지금 실전) 합친 뒤
         **하루 최대 K** 로 자른다 (K = 4·6·8·10·제한 없음)
· 표 — 앞(~2018) · 뒤(2019~) 따로 · 끝 자산 · 낙폭 · 1년 산 것 · 1년 산 날 · 1년 후보 뜬 날(기회)
"""
import io
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import omni_lab as O  # noqa: E402

_L = os.path.join(O._DATA, "_labs")
_시드 = 5_000_000.0
_비중 = 0.20
_이자 = 0.025
_낙한 = -12.0
_분할 = "2019"
_밖 = io.open(os.path.join(_L, os.environ.get("LAB_OUT") or "multi_lab.txt"), "w", encoding="utf-8")


def 찍기(*a):
    s = " ".join(str(z) for z in a)
    print(s, flush=True)
    _밖.write(s + "\n")
    _밖.flush()


def 읽기():
    스펙 = json.load(io.open(os.path.join(_L, "multi_rules_spec.json"), encoding="utf-8"))["규칙"]
    후보 = {}          # 규칙 → {날짜: [pick…]}
    대조 = {}          # 규칙 → 같은 자료로 원래 시뮬이 낸 {대조끝, 대조산, 대조낙}
    끝날 = {}          # 무리 → 그 내보내기가 본 마지막 날
    for 이름 in ("multi_cand_own.jsonl", "multi_cand_live.jsonl"):
        p = os.path.join(_L, 이름)
        if not os.path.exists(p):
            raise SystemExit(f"🛑 {이름} 이 없다 — own_lab OWN_EXPORT · gate7 ONLY=MULTIDUMP 를 먼저")
        for 줄 in io.open(p, encoding="utf-8"):
            if 줄.strip():
                z = json.loads(줄)
                if z["규칙"] == "_머리":
                    끝날[z["무리"]] = z["끝날"]
                    continue
                if "대조끝" in z:
                    대조[z["규칙"]] = z
                    continue
                if z["날"] in 후보.setdefault(z["규칙"], {}):
                    raise SystemExit(f"🛑 {z['규칙']} {z['날']} 가 두 번 — 내보내기를 두 번 했나 (multi_cand_own.jsonl 은 덧붙인다)")
                후보[z["규칙"]][z["날"]] = z["후보"]
    return 스펙, 후보, 대조, 끝날


def main():
    스펙, 후보, 대조, 끝날 = 읽기()
    주가 = O.수정주가(())
    날 = sorted(주가)
    # ⚠️ 10/1 독립 검사: 단계 사이에 저녁 자료가 붙으면 후보 파일끼리·여기 주가와 끝 날이 다르다 — 섞으면 안 된다
    if len(set(끝날.values())) != 1 or 날[-1] not in 끝날.values():
        raise SystemExit(f"🛑 자료 끝 날이 다르다 — 후보 파일 {sorted(set(끝날.values()))} · 지금 주가 {날[-1]} · 처음부터 다시")
    자리i = {d: k for k, d in enumerate(날)}
    규칙 = {r["id"]: r for r in 스펙}
    규칙["L00"] = {"id": "L00", "무리": "실전 규칙(지금 화면)", "조건": "rule_def 그대로", "자리": 99, "짧음": False,
                  "앞시작": min(후보.get("L00") or {"0": 0})[:4], "또사기": True}
    없 = [k for k in 규칙 if k not in 후보]
    찍기("=" * 122)
    찍기("  ── MULTI — 여러 규칙 한 계좌 (무리 규칙 + 실전 규칙 · OR) ──")
    찍기(f"     규칙 {len(규칙)}개 (무리 {len(스펙)} + 실전 1) · 후보 파일에 없는 규칙 {없 or '없음'}")
    찍기("     계좌: 시드 500만 · 비중 20% · 거래대금 1% · 현금 연 2.5% · 들고 있는 종목 = 전날 종가 평가 · 비용은 결과에 들어 있다")
    찍기("     ⚠️ 비중 20%는 시뮬 가정이다 (화면에 안 쓴다)")
    찍기("=" * 122)
    for k in 없:
        규칙.pop(k)

    def 한거래(p):
        """몫들 가중 결과% (None 몫은 뺀다)"""
        s = w = 0.0
        for 비율, r, _ in p["몫"]:
            if r is not None:
                s += 비율 * r
                w += 비율
        return s / w if w else None

    # ── 신호 세기 = 앞 기간(~2018) 그 규칙 후보(제 자리까지)의 이김% ──
    세기 = {}
    for k, r in 규칙.items():
        결 = [한거래(p) for d, ps in 후보[k].items() if d[:4] < _분할 for p in ps[:r["자리"]]]
        결 = [z for z in 결 if z is not None]
        세기[k] = (sum(1 for z in 결 if z > 0) / len(결) * 100 if 결 else 0.0, len(결))
    순서 = sorted(규칙, key=lambda k: -세기[k][0])

    def 시뮬(켜, K=None, 시작년=None, 끝년=None, 곡돌려=False):
        """켜 = 규칙 id 들 · K = 하루 최대(None 이면 제한 없음)"""
        켜 = [k for k in 순서 if k in 켜]
        # ⚠️ 10/1 독립 검사: 날[0] 은 2010 보다 1년 넘게 앞이다(사건은 260일 뒤부터) — 빈 해가 「해」를 늘린다 ⇒ own·gate7 처럼 2010 부터
        a = [j for j, d in enumerate(날) if d[:4] >= (시작년 or "2010")]
        시작i = a[0]
        현금, 보유, 곡, 산, 산날, 뜬날 = _시드, [], [], 0, 0, 0
        여분모자람 = 0
        새날 = {k: 0 for k in 켜}
        i = 시작i
        for i in range(시작i, len(날)):
            d = 날[i]
            if 끝년 and d[:4] > 끝년:
                break
            남 = []
            for q in 보유:
                if q["청산"] <= i:
                    현금 += q["주수"] * q["원시"] * (1 + q["결과"] / 100)
                else:
                    남.append(q)
            보유 = 남
            현금 *= (1 + _이자 / 245)
            _전 = 주가[날[i - 1]] if i >= 1 else {}
            평 = 현금 + sum(q["주수"] * q["원시"] * ((_전.get(q["code"]) or (q["매수수정"],))[0] / q["매수수정"])
                          for q in 보유)
            든 = {q["code"] for q in 보유}
            골, 오늘, 뜬 = [], set(), []
            for k in 켜:
                ps = 후보[k].get(d)
                if not ps or d[:4] < 규칙[k]["앞시작"]:
                    continue
                n = 0
                또 = 규칙[k].get("또사기")
                for p in ps:
                    if n >= 규칙[k]["자리"]:
                        break
                    if p["code"] in 오늘 or (not 또 and p["code"] in 든):
                        continue
                    골.append(p)
                    오늘.add(p["code"])
                    n += 1
                # 「뜬」 = 이 규칙이 **실제로 하나라도 골랐다** (후보는 떴는데 전부 들고 있거나 겹친 날은 안 센다 · 10/1 독립 검사)
                if n:
                    뜬.append(k)
                # 내보낸 후보가 「제 자리 + 여분 30」 에서 잘렸는데 자리를 다 못 채웠다 = own_lab 혼자 판과 달라질 수 있는 날
                if not 또 and n < 규칙[k]["자리"] and len(ps) >= 규칙[k]["자리"] + 30:
                    여분모자람 += 1
            if 뜬:
                뜬날 += 1
                if len(뜬) == 1:
                    새날[뜬[0]] += 1
            if K is not None:
                골 = 골[:K]
            샀다 = False
            for p in 골:
                쓸 = min(평 * _비중, 현금, (p.get("대금억") or 0) * 1e8 * 0.01)
                총 = int(쓸 // p["원시"])
                if 총 < len(p["몫"]) or 총 * p["원시"] > 현금:
                    continue
                넣 = False
                for 비율, r, 청d in p["몫"]:
                    if r is None:
                        continue
                    주 = int(총 * 비율)
                    if 주 < 1 or 주 * p["원시"] > 현금:
                        continue
                    현금 -= 주 * p["원시"]
                    보유.append({"주수": 주, "원시": p["원시"], "결과": r, "청산": 자리i[청d], "code": p["code"],
                                 "매수수정": p["매수"]})
                    넣 = True
                if 넣:
                    산 += 1
                    샀다 = True
            if 샀다:
                산날 += 1
            곡.append(평)
        _막 = 주가[날[min(i, len(날) - 1)]] if 보유 else {}
        끝 = 현금 + sum(q["주수"] * q["원시"] * ((_막.get(q["code"]) or (q["매수수정"],))[0] / q["매수수정"]) for q in 보유)
        해 = max(len(곡) / 245, 0.1)
        연 = ((끝 / _시드) ** (1 / 해) - 1) * 100 if 끝 > 0 else -100
        최고, 낙 = _시드, 0.0
        for v in 곡:
            최고 = max(최고, v)
            낙 = min(낙, v / 최고 - 1)
        out = {"끝": 끝, "연": 연, "낙": 낙 * 100, "산": 산, "산날": 산날, "뜬날": 뜬날, "해": 해,
               "현금만": _시드 * (1 + _이자 / 245) ** len(곡), "새날": 새날, "여분": 여분모자람}
        if 곡돌려:
            out["곡"] = 곡
        return out

    def 줄(라, r):
        return (f"  {라:<40}{r['끝']:>14,.0f}원{r['연']:>+7.1f}%{r['낙']:>7.1f}%"
                f"{r['산'] / r['해']:>8.0f}{r['산날'] / r['해']:>8.0f}{r['뜬날'] / r['해']:>8.0f}"
                f"{'' if r['낙'] >= _낙한 else '  ⚠️낙폭 한계 밖'}")
    머 = f"  {'':<40}{'끝 자산':>15}{'연':>8}{'낙폭':>7}{'1년 산':>8}{'산 날':>8}{'뜬 날':>8}"

    # ── ① 대조 — 혼자 돌리면 원래 판 숫자가 나와야 한다 ──
    # ⚠️ 10/1 독립 검사: 스펙의 「뒤끝」(9/29 자료)이 아니라 **같은 자료로 원래 시뮬이 낸 값**(대조끝)과 견준다.
    #    무리 규칙 = 끝 자산·산 수 · 실전 L00 = 산 수·낙폭 (gate7 끝 자산은 들고 있는 것을 산 값으로 세 기말 평가가 다르다)
    찍기("\n  ① 대조 — 규칙마다 혼자 (뒤 2019~ · 제 자리) · 같은 자료로 원래 시뮬이 낸 값과 같아야 한다")
    찍기(f"  {'규칙':<6}{'무리':<24}{'신호 세기(앞 이김%)':>18}{'앞 거래':>8}{'끝 자산(여기)':>16}{'원래 시뮬':>16}{'산(여기/원래)':>14}{'낙폭(여기/원래)':>17}  같나")
    틀림 = 0
    for k in 순서:
        r = 규칙[k]
        rr = 시뮬([k], 시작년=_분할)
        원 = 대조.get(k)
        if 원 is None:
            같 = "❌ 대조 값 없음"
        elif k == "L00":
            같 = "✅" if (rr["산"] == 원["대조산"] and abs(rr["낙"] - 원["대조낙"]) <= 0.05) else "❌"
        else:
            같 = "✅" if (rr["산"] == 원["대조산"] and abs(rr["끝"] - 원["대조끝"]) <= 2.0) else "❌"
        if 같 != "✅":
            틀림 += 1
        찍기(f"  {k:<6}{r['무리'][:22]:<24}{세기[k][0]:>17.1f}%{세기[k][1]:>8}{rr['끝']:>16,.0f}"
             f"{(format(round(원['대조끝']), ',') if 원 else '-'):>16}"
             f"{(str(rr['산']) + '/' + str(원['대조산']) if 원 else '-'):>14}"
             f"{(format(rr['낙'], '.1f') + '/' + format(원['대조낙'], '.1f') if 원 else '-'):>17}  {같}"
             f"{'  여분 모자란 날 ' + str(rr['여분']) if rr['여분'] else ''}"
             f"{'  ⚠️ 앞 5년 미만' if r.get('짧음') else ''}")
    찍기(f"  → 대조 틀림 {틀림}개 (무리 = 끝 자산 ±2원·산 수 · 실전 = 산 수·낙폭 ±0.05%p)")
    if 틀림:
        찍기("  🛑 대조가 틀렸다 — 합친 숫자를 믿을 수 없다. 아래는 참고로만 찍는다")

    무리 = [k for k in 순서 if k != "L00"]
    긴 = [k for k in 무리 if not 규칙[k].get("짧음")]
    창 = (("앞 ~2018", None, str(int(_분할) - 1)), ("뒤 2019~", _분할, None))

    # ── ② 실전 + 무리 규칙 하나씩 (OR) — 제한 없음 · K=6 ──
    찍기("\n  ② 실전 규칙 + 무리 규칙 하나씩 (OR) — 실전만과 견줌 · 「새 날」= 그 규칙만 종목을 고른 날(1년)")
    for 이름, a, b in 창:
        찍기(f"\n   [{이름}]" + 머)
        밑 = 시뮬(["L00"], 시작년=a, 끝년=b)
        찍기(줄("실전만", 밑))
        for k in 무리:
            rr = 시뮬(["L00", k], 시작년=a, 끝년=b)
            찍기(줄(f"+ {k} {규칙[k]['무리'][:14]}", rr)
                 + f"  지금의 {rr['끝'] / 밑['끝'] * 100:.0f}% · 새 날 {rr['새날'].get(k, 0) / rr['해']:.0f}/년"
                 + ("  ⚠️짧음" if 규칙[k].get("짧음") else ""))

    # ── ③ 전부 같이 — 하루 최대 K ──
    for 묶이름, 켜 in (("실전 + 무리 20개 전부", ["L00"] + 무리), ("실전 + 긴 자료(5년+) 무리만", ["L00"] + 긴),
                     ("무리 20개만 (실전 없이)", 무리)):
        찍기(f"\n  ③ {묶이름} — 하루 최대 종목 수별 ⚠️ 하루 최대는 계좌 전체 상한 (규칙마다 제 자리는 그대로)")
        for 이름, a, b in 창:
            찍기(f"\n   [{이름}]" + 머)
            for K in (4, 6, 8, 10, None):
                rr = 시뮬(켜, K=K, 시작년=a, 끝년=b)
                찍기(줄(f"하루 최대 {K or '제한 없음'}", rr))

    # ── ④ 하나씩 쌓기 — 앞 기간에서 「새 날」 많은 순으로 고르고 · 앞에서 돈이 늘 때만 넣는다 · 뒤는 확인만 ──
    for K in (6, 10):
        찍기(f"\n  ④ 하나씩 쌓기 (하루 최대 {K}) — 앞(~2018)에서 새 날 많은 것부터 · 앞 끝 자산이 늘고 낙폭 한계 안일 때만 넣음 · 뒤는 증분 확인")
        찍기(f"  {'단계':<34}{'앞 끝 자산':>14}{'앞 낙폭':>8}{'앞 1년 산날':>11}{'뒤 끝 자산':>14}{'뒤 낙폭':>8}{'뒤 1년 산날':>11}  뒤 증분")
        쌓 = ["L00"]
        앞밑 = 시뮬(쌓, K=K, 끝년=str(int(_분할) - 1))
        뒤밑 = 시뮬(쌓, K=K, 시작년=_분할)
        찍기(f"  {'실전만':<34}{앞밑['끝']:>14,.0f}{앞밑['낙']:>7.1f}%{앞밑['산날'] / 앞밑['해']:>11.0f}"
             f"{뒤밑['끝']:>14,.0f}{뒤밑['낙']:>7.1f}%{뒤밑['산날'] / 뒤밑['해']:>11.0f}")
        남 = list(무리)
        while 남:
            잰 = []
            for k in 남:
                rr = 시뮬(쌓 + [k], K=K, 끝년=str(int(_분할) - 1))
