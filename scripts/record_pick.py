def 섹터규칙맞나(code, sq, kk, c1, 섹터표):
    """그 종목이 속한 섹터의 규칙에 맞나. 섹터가 없으면 False

    ⚠️ 한 규칙 **안에서는 AND** (볼린저 그리고 낙폭) · 규칙 **끼리는 OR**
    """
    섹 = 섹터표.get(code)
