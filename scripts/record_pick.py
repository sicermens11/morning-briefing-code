    bw, bt, nw, nt = 규
    if kk < max(bw, nw):
        return False, 섹
    m = st.mean(sq[kk - bw + 1:kk + 1])
    sd2 = st.pstdev(sq[kk - bw + 1:kk + 1]) or 1e-9
    볼2 = (c1 - m) / (2 * sd2)
    if 볼2 > bt:
        return False, 섹
