#  ⭐⭐ **08:50 -> 08:55** (2026-09-14 지시). 판정 시각을 5분 늦췄다.
#     2026-09-14 에 세 시각 예상체결가를 **실제 시가**와 맞춰 봤다(21종목):
#         08:50  평균 오차 0.95%p   중앙값 0.14   최대 8.86
#         08:55  평균 오차 0.60%p   중앙값 0.36   최대 2.85
#         09:00  평균 오차 0.04%p   ← **이미 시가 그 자체다. 그때는 못 산다**
#     동시호가 초반은 호가가 얇아 **크게 빠진 것처럼 과장된다** — 하필
#     우리가 찾는 종목에서 오차가 가장 크다(메디아나 08:50 −10.98% →
#     08:55 −4.51% → 시가 −2.32%). 08:55 면 09:00 까지 주문 넣을 5분이 남는다.
#     ⚠️ 표본이 하루뿐이라 **확정이 아니다.** `fetch_antc.py` 가 08:50 값도
