# ⭐ ㉣ **섹터규칙 종목은 시총 상한을 안 본다** (2026-09-16 반영 · 사용자 결정)
#    전에는 시총 문(300~2,000억)이 모든 규칙보다 먼저라 섹터규칙 6개가 원전·조선·방산 **대형주에
#    한 번도 안 걸렸다** (record_pick 748줄이 섹터 판정 776줄보다 앞). BIG4·5·6 4관문:
