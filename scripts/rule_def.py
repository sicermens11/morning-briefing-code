# ⚠️ 문턱가 = 어제종가 x (1 + (중앙갭 + 상대갭문턱) / 100)
#    중앙갭은 **08:50 에야** 안다. 그래서 08:00 에는 **범위**로만 줄 수 있다.
#    ⭐ 실측 (2026-09-11 · 최근 259 거래일 · 전 종목 시가 중앙갭):
#         5%  -0.79   10%  -0.40   25%  0.00   중앙 0.00
#        75%  +0.13   90%  +0.40   95%  +0.83
#       => **열에 아홉 날이 -0.40% ~ +0.40%** 안에 든다
중앙갭아래 = -0.40      # 10 분위
중앙갭위 = 0.40         # 90 분위


def 호가단위(값):
    """그 값대의 호가 단위 (2023년 통일 기준)"""
    for 위, 단 in ((2000, 1), (5000, 5), (20000, 10), (50000, 50),
                   (200000, 100), (500000, 500)):
        if 값 < 위:
            return 단
    return 1000


def 매수범위(어제종가):
    """(아래, 위) — 08:50 에 걸 값이 들어올 **자리**. 호가 단위로 맞춘다

    ⚠️ 「이 범위 안에서 산다」가 아니라 **「문턱가가 이 범위에 들어온다」**다.
       실제로는 08:50 에 한 값으로 정해진다
    """
    def _맞춤(v):
        단 = 호가단위(v)
        return int(round(v / 단) * 단)
    아 = _맞춤(어제종가 * (1 + (중앙갭아래 + 상대갭문턱) / 100))
    위 = _맞춤(어제종가 * (1 + (중앙갭위 + 상대갭문턱) / 100))
    return 아, 위


def _몫이름(비율):
    """「반」 또는 「40%」 — 한줄() 이 쓴다. 50:50 이 아니면 숫자로 적는다"""
    return "반" if abs(비율 - .5) < 1e-9 else f"{비율 * 100:g}%"


