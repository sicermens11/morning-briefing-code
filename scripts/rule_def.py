def 업종이름(업종명):
    r"""표준산업분류 업종명 -> 업종지수 이름. 못 이으면 None

    ⚠️ gate7_lab.업종지수() 와 **같은 차례**로 찾는다 (똑같이 맞아떨어져야 한다):
       ① 표에 그대로 있나  ② 한쪽이 다른 쪽을 품나
    """
    나 = str(업종명 or "")
    if 나 in 업종맵:
        return 업종맵[나]
    for k, v in 업종맵.items():
        if k and (k in 나 or 나 in k):
            return v
    return None


def 업종문따로(업종명):
    r"""그 업종 규칙이 **제 문**(재무·대금)을 갖나 — 그러면 실전 고리는 바깥 문을 건너뛴다"""
